import ExcelJS from 'exceljs';
import { Exporter, ExporterResult, ReportDataset, SectionPayload } from './exporter.types';

const NAVY_FILL = 'FF1A365D';
const SUMMARY_SHEET = 'Summary';

function sanitizeSheetName(raw: string): string {
  const clean = raw.replace(/[\\/\?\*\[\]:]/g, '').trim().slice(0, 28);
  return clean.length > 0 ? clean : 'Sheet';
}

function uniqueSheetName(workbook: ExcelJS.Workbook, base: string): string {
  let name = sanitizeSheetName(base);
  let suffix = 2;
  while (workbook.getWorksheet(name)) {
    name = sanitizeSheetName(`${base} ${suffix}`);
    suffix++;
  }
  return name;
}

function writeSummarySheet(
  workbook: ExcelJS.Workbook,
  dataset: ReportDataset,
  requestedSectionKeys: string[],
): void {
  const sheet = workbook.addWorksheet(SUMMARY_SHEET);
  sheet.columns = [{ width: 32 }, { width: 36 }];

  sheet.addRow([dataset.reportTitle]).font = { bold: true, size: 16, color: { argb: NAVY_FILL } };
  sheet.addRow([dataset.contextSubtitle]);
  sheet.addRow([`Generated: ${dataset.generatedAt.toLocaleString('en-US')}`]);
  sheet.addRow([`Generated by: ${dataset.generatedBy}`]);
  sheet.addRow([]);

  for (const key of requestedSectionKeys) {
    const section = dataset.sections[key];
    if (!section || section.type !== 'metrics') continue;

    const titleRow = sheet.addRow([section.label]);
    titleRow.font = { bold: true, size: 12, color: { argb: NAVY_FILL } };

    section.metrics.forEach((m) => {
      const row = sheet.addRow([m.label, m.value]);
      row.getCell(1).font = { color: { argb: 'FF4B5563' } };
      row.getCell(2).font = { bold: true };
    });
    sheet.addRow([]);
  }
}

function writeChartSheet(
  workbook: ExcelJS.Workbook,
  section: Extract<SectionPayload, { type: 'chart' }>,
): void {
  const sheet = workbook.addWorksheet(uniqueSheetName(workbook, section.label));

  const headerCells = ['Label', ...section.data.datasets.map((d) => d.label)];
  const headerRow = sheet.addRow(headerCells);
  headerRow.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  headerRow.eachCell((cell) => {
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: NAVY_FILL } };
  });
  sheet.views = [{ state: 'frozen', ySplit: 1 }];

  section.data.labels.forEach((label, idx) => {
    const row = [label, ...section.data.datasets.map((d) => d.values[idx] ?? 0)];
    sheet.addRow(row);
  });

  sheet.columns.forEach((col) => {
    col.width = 18;
  });
  if (sheet.columns[0]) sheet.columns[0].width = 26;
}

function writeTableSheet(
  workbook: ExcelJS.Workbook,
  section: Extract<SectionPayload, { type: 'table' }>,
): void {
  const sheet = workbook.addWorksheet(uniqueSheetName(workbook, section.label));

  sheet.columns = section.columns.map((c) => ({
    header: c.header,
    key: c.key,
    width: c.width ?? 20,
  }));

  const headerRow = sheet.getRow(1);
  headerRow.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  headerRow.eachCell((cell) => {
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: NAVY_FILL } };
  });
  sheet.views = [{ state: 'frozen', ySplit: 1 }];

  section.rows.forEach((row) => {
    sheet.addRow(row);
  });
}

export const excelExporter: Exporter = {
  format: 'excel',
  async generate(dataset: ReportDataset, requestedSectionKeys: string[]): Promise<ExporterResult> {
    const workbook = new ExcelJS.Workbook();
    workbook.creator = dataset.generatedBy;
    workbook.created = dataset.generatedAt;
    workbook.title = dataset.reportTitle;

    writeSummarySheet(workbook, dataset, requestedSectionKeys);

    for (const key of requestedSectionKeys) {
      const section = dataset.sections[key];
      if (!section) continue;

      if (section.type === 'chart') writeChartSheet(workbook, section);
      else if (section.type === 'table') writeTableSheet(workbook, section);
    }

    const arrayBuffer = await workbook.xlsx.writeBuffer();
    const buffer = Buffer.from(arrayBuffer as ArrayBuffer);
    return {
      buffer,
      mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
      extension: 'xlsx',
    };
  },
};
